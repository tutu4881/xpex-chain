#!/bin/sh
set -eu

echo "======================================"
echo "        XPEX CHAIN — RAILWAY"
echo "======================================"

HOME_DIR="/data/.exampleapp"
IMAGE_GENESIS="/opt/xpex/genesis.json"
if [ "${XPEX_NETWORK:-mainnet}" = "staging" ] && [ -f /opt/xpex/genesis.staging.json ]; then
    IMAGE_GENESIS="/opt/xpex/genesis.staging.json"
fi
echo "Genesis template: $IMAGE_GENESIS"
RESET_MARKER="$HOME_DIR/.chain-reset-id"

mkdir -p "$HOME_DIR/config"
mkdir -p "$HOME_DIR/data"

echo "PORT=${PORT:-not-set}"
echo "RAILWAY_TCP_PROXY_DOMAIN=${RAILWAY_TCP_PROXY_DOMAIN:-not-set}"
echo "RAILWAY_TCP_PROXY_PORT=${RAILWAY_TCP_PROXY_PORT:-not-set}"

if [ ! -f "$IMAGE_GENESIS" ]; then
    echo "ERROR: genesis template not found at $IMAGE_GENESIS"
    exit 1
fi

# --------------------------------------------------
# Initialize config (first start on an empty volume)
# --------------------------------------------------

if [ ! -f "$HOME_DIR/config/config.toml" ]; then
    echo "Initializing XPEX configuration..."

    /usr/local/bin/xpexd init XPEX \
        --home "$HOME_DIR" \
        --chain-id xpex-1 \
        --overwrite
fi

# --------------------------------------------------
# Controlled chain reset
#
# Railway gives no shell on the volume, so a reset is driven by a variable:
# set CHAIN_RESET_ID to any new value and the NEXT start wipes the chain
# database and re-installs the genesis baked into the image. node_key.json and
# the validator key are kept. Starting again with the same value does nothing,
# so it can stay set safely.
# --------------------------------------------------

CURRENT_RESET_ID=""
if [ -f "$RESET_MARKER" ]; then
    CURRENT_RESET_ID="$(cat "$RESET_MARKER")"
fi

if [ -n "${CHAIN_RESET_ID:-}" ] && [ "$CHAIN_RESET_ID" != "$CURRENT_RESET_ID" ]; then
    echo "CHAIN_RESET_ID changed ('$CURRENT_RESET_ID' -> '$CHAIN_RESET_ID'): wiping chain data"
    rm -rf "$HOME_DIR/data"
    mkdir -p "$HOME_DIR/data"
    rm -f "$HOME_DIR/config/genesis.json" "$HOME_DIR/config/addrbook.json"
    printf '{\n  "height": "0",\n  "round": 0,\n  "step": 0\n}\n' > "$HOME_DIR/data/priv_validator_state.json"
    printf '%s' "$CHAIN_RESET_ID" > "$RESET_MARKER"
fi

if [ ! -f "$HOME_DIR/config/genesis.json" ]; then
    echo "Installing genesis from image..."
    cp "$IMAGE_GENESIS" "$HOME_DIR/config/genesis.json"
else
    echo "Genesis already exists in persistent volume."
fi

echo "Genesis chain_id: $(python3 -c "import json;print(json.load(open('$HOME_DIR/config/genesis.json'))['chain_id'])")"

# --------------------------------------------------
# Validator key
# --------------------------------------------------

# NODE_ROLE=fullnode keeps the random consensus key generated by `init`, so a
# second node can never sign with the validator key (double-sign = slashing).
if [ "${NODE_ROLE:-validator}" = "fullnode" ]; then
    echo "NODE_ROLE=fullnode: validator key NOT installed."
else
    if [ -z "${VALIDATOR_KEY_JSON_B64:-}" ]; then
        echo "ERROR: VALIDATOR_KEY_JSON_B64 is not set"
        exit 1
    fi

    echo "Installing validator key..."

    echo "$VALIDATOR_KEY_JSON_B64" | base64 -d \
        > "$HOME_DIR/config/priv_validator_key.json"

    chmod 600 "$HOME_DIR/config/priv_validator_key.json"

    echo "Validator key installed."
fi

echo "Node ID: $(/usr/local/bin/xpexd comet show-node-id --home "$HOME_DIR" 2>/dev/null || echo unknown)"

# --------------------------------------------------
# CometBFT RPC
# --------------------------------------------------

echo "Configuring CometBFT RPC..."

python3 - "$HOME_DIR/config/config.toml" <<'PY'
from pathlib import Path
import sys

p = Path(sys.argv[1])
s = p.read_text()

start = s.index("[rpc]")
end = s.find("\n[", start + 1)

if end == -1:
    end = len(s)

section = s[start:end]

lines = section.splitlines()

for i, line in enumerate(lines):
    if line.startswith("laddr = "):
        lines[i] = 'laddr = "tcp://0.0.0.0:26657"'

s = s[:start] + "\n".join(lines) + s[end:]

p.write_text(s)
PY

# --------------------------------------------------
# Cosmos REST API
# --------------------------------------------------

echo "Configuring Cosmos REST API..."

python3 - "$HOME_DIR/config/app.toml" "8080" <<'PY'
from pathlib import Path
import sys

p = Path(sys.argv[1])
port = sys.argv[2]

s = p.read_text()

start = s.index("[api]")
end = s.find("\n[", start + 1)

if end == -1:
    end = len(s)

section = s[start:end]

lines = section.splitlines()

for i, line in enumerate(lines):
    if line.startswith("enable = "):
        lines[i] = "enable = true"

    if line.startswith("address = "):
        lines[i] = f'address = "tcp://0.0.0.0:{port}"'

s = s[:start] + "\n".join(lines) + s[end:]

p.write_text(s)
PY

# --------------------------------------------------
# gRPC
# --------------------------------------------------

echo "Configuring gRPC..."

python3 - "$HOME_DIR/config/app.toml" <<'PY'
from pathlib import Path
import sys

p = Path(sys.argv[1])
s = p.read_text()

start = s.index("[grpc]")
end = s.find("\n[", start + 1)

if end == -1:
    end = len(s)

section = s[start:end]

lines = section.splitlines()

for i, line in enumerate(lines):
    if line.startswith("enable = "):
        lines[i] = "enable = true"

    if line.startswith("address = "):
        lines[i] = 'address = "0.0.0.0:9090"'

s = s[:start] + "\n".join(lines) + s[end:]

p.write_text(s)
PY
# --------------------------------------------------
# P2P
# --------------------------------------------------

echo "Configuring P2P..."

P2P_EXTERNAL_ADDRESS="${P2P_EXTERNAL_ADDRESS:-}"
PERSISTENT_PEERS="${PERSISTENT_PEERS:-}"

python3 - "$HOME_DIR/config/config.toml" "$P2P_EXTERNAL_ADDRESS" "$PERSISTENT_PEERS" <<'PY'
from pathlib import Path
import sys

p = Path(sys.argv[1])
external_address = sys.argv[2]
persistent_peers = sys.argv[3]

s = p.read_text()

start = s.index("[p2p]")
end = s.find("\n[", start + 1)

if end == -1:
    end = len(s)

section = s[start:end]
lines = section.splitlines()

for i, line in enumerate(lines):
    if line.startswith("external_address = "):
        lines[i] = f'external_address = "{external_address}"'

    if line.startswith("persistent_peers = "):
        lines[i] = f'persistent_peers = "{persistent_peers}"'

s = s[:start] + "\n".join(lines) + s[end:]

p.write_text(s)
PY

echo "P2P_EXTERNAL_ADDRESS=$P2P_EXTERNAL_ADDRESS"
echo "PERSISTENT_PEERS=$PERSISTENT_PEERS"
# --------------------------------------------------
# Block time (optional)
#
# TIMEOUT_COMMIT=15s makes the validator wait that long between blocks
# (CometBFT [consensus] timeout_commit). Unset = leave config.toml untouched.
# Fewer blocks = slower database growth and less RAM/CPU. Only the validator
# produces blocks, so this only matters on the NODE_ROLE=validator service.
# --------------------------------------------------

if [ -n "${TIMEOUT_COMMIT:-}" ]; then
    echo "Setting consensus timeout_commit=$TIMEOUT_COMMIT"
    python3 - "$HOME_DIR/config/config.toml" "$TIMEOUT_COMMIT" <<'PY'
from pathlib import Path
import re
import sys

p = Path(sys.argv[1])
value = sys.argv[2].strip()

if not re.fullmatch(r"\d+(ms|s|m)", value):
    print(f"WARNING: TIMEOUT_COMMIT='{value}' is not like 15s/500ms/1m - ignored")
    sys.exit(0)

s = p.read_text()
start = s.find("[consensus]")
if start == -1:
    print("WARNING: [consensus] section not found - timeout_commit unchanged")
    sys.exit(0)
end = s.find("\n[", start + 1)
if end == -1:
    end = len(s)

lines = s[start:end].splitlines()
changed = False
for i, line in enumerate(lines):
    if line.startswith("timeout_commit = "):
        lines[i] = f'timeout_commit = "{value}"'
        changed = True

if not changed:
    print("WARNING: timeout_commit key not present in [consensus] - unchanged")
    sys.exit(0)

p.write_text(s[:start] + "\n".join(lines) + s[end:])
print(f"timeout_commit set to {value}")
PY
fi

# --------------------------------------------------
# Gas prices
# --------------------------------------------------

if [ -z "${MINIMUM_GAS_PRICES:-}" ]; then
    MINIMUM_GAS_PRICES="0uxpx"
fi

echo "MINIMUM_GAS_PRICES=$MINIMUM_GAS_PRICES"

# --------------------------------------------------
# Verify configuration
# --------------------------------------------------

echo "======================================"
echo "FINAL CONFIGURATION"
echo "======================================"

echo "--- RPC ---"
sed -n '/^\[rpc\]/,/^\[/p' "$HOME_DIR/config/config.toml"

echo "--- API ---"
sed -n '/^\[api\]/,/^\[/p' "$HOME_DIR/config/app.toml"

echo "--- gRPC ---"
sed -n '/^\[grpc\]/,/^\[/p' "$HOME_DIR/config/app.toml"

echo "--- consensus timeout ---"
grep -n "^timeout_commit" "$HOME_DIR/config/config.toml" || echo "timeout_commit not found"

echo "======================================"
echo "Starting XPEX..."
echo "======================================"

exec /usr/local/bin/xpexd start \
    --home "$HOME_DIR" \
    --minimum-gas-prices "$MINIMUM_GAS_PRICES"
